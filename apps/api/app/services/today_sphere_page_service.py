def _provider_method(client: object) -> tuple[Callable[..., object], str]:
    for name in ("generate_json", "generate", "complete", "_generate_text"):
        method = getattr(client, name, None)
        if callable(method):
            return method, name
    if callable(client):
        return client, "__call__"
    raise TypeError("llm client has no supported call method")


def _provider_kwargs(
    method: Callable[..., object],
    method_name: str,
    deadline_at: float,
) -> dict[str, Any]:
    try:
        parameters = inspect.signature(method).parameters
    except (TypeError, ValueError):
        parameters = {}
    accepts_kwargs = any(
        parameter.kind is inspect.Parameter.VAR_KEYWORD
        for parameter in parameters.values()
    )

    def supports(name: str) -> bool:
        return accepts_kwargs or name in parameters

    kwargs: dict[str, Any] = {}
    if supports("max_output_tokens"):
        kwargs["max_output_tokens"] = SPHERE_NATAL_MAX_OUTPUT_TOKENS
    elif supports("max_tokens"):
        kwargs["max_tokens"] = SPHERE_NATAL_MAX_OUTPUT_TOKENS
    if supports("timeout_seconds"):
        kwargs["timeout_seconds"] = SPHERE_NATAL_TIMEOUT_SECONDS
    elif supports("timeout"):
        kwargs["timeout"] = SPHERE_NATAL_TIMEOUT_SECONDS
    if supports("deadline_at"):
        kwargs["deadline_at"] = deadline_at
    if supports("json_object"):
        kwargs["json_object"] = True
    if supports("json_schema"):
        kwargs["json_schema"] = _SPHERE_NATAL_JSON_SCHEMA
    return kwargs


def _decode_provider_value(value: object) -> object:
    if isinstance(value, (str, bytes)):
        if isinstance(value, bytes):
            return value.decode("utf-8")
        return value
    if isinstance(value, Mapping):
        if "paragraphs" in value:
            return value
        for key in ("text", "content", "output", "response"):
            if key in value:
                return _decode_provider_value(value[key])
        return value
    raw = getattr(value, "text", getattr(value, "content", None))
    return _decode_provider_value(raw) if raw is not None else value


async def _call_natal_provider(client: object, prompt: str) -> object:
    method, method_name = _provider_method(client)
    deadline_at = time.monotonic() + SPHERE_NATAL_TIMEOUT_SECONDS
    result = method(prompt, **_provider_kwargs(method, method_name, deadline_at))
    return await asyncio.wait_for(result, timeout=SPHERE_NATAL_TIMEOUT_SECONDS) if inspect.isawaitable(result) else result


def _validate_natal_provider_response(
    raw_response: object,
    allowed_fact_ids: frozenset[str],
    available_special_points: frozenset[str],
) -> TodaySphereNatalContent:
    raw_response = _decode_provider_value(raw_response)
    if isinstance(raw_response, str):
        text = raw_response.strip()
        if "```" in text:
            text = text.replace("```json", "").replace("```", "").strip()
        try:
            parsed: object = json.loads(text)
        except (TypeError, ValueError, json.JSONDecodeError) as exc:
            raise _NatalNarrativeError("schema_invalid") from exc
    else:
        parsed = raw_response

    if not isinstance(parsed, Mapping) or set(parsed) != {"paragraphs"}:
        raise _NatalNarrativeError("schema_invalid")
    raw_paragraphs = parsed["paragraphs"]
    if not isinstance(raw_paragraphs, list) or not 1 <= len(raw_paragraphs) <= 4:
        raise _NatalNarrativeError("schema_invalid")

    paragraphs: list[TodaySphereNatalParagraph] = []
    for raw_paragraph in raw_paragraphs:
        if not isinstance(raw_paragraph, Mapping) or set(raw_paragraph) != {"text", "sourceFactIds"}:
            raise _NatalNarrativeError("schema_invalid")
        text_value = raw_paragraph["text"]
        source_ids = raw_paragraph["sourceFactIds"]
        if not isinstance(text_value, str) or not text_value.strip():
            raise _NatalNarrativeError("schema_invalid")
        if not isinstance(source_ids, list) or not source_ids:
            raise _NatalNarrativeError("claim_binding")
        if any(not isinstance(source_id, str) or not source_id.strip() for source_id in source_ids):
            raise _NatalNarrativeError("claim_binding")
        if len(source_ids) != len(set(source_ids)) or not set(source_ids).issubset(allowed_fact_ids):
            raise _NatalNarrativeError("claim_binding")
        clean_text = sanitize_narrative_text(text_value)
        if clean_text is None:
            raise _NatalNarrativeError("schema_invalid")
        # Known fragments of the retired natal templates must never enter the
        # cache or wire response.  Keep this fail-closed at the provider
        # boundary so the existing unavailable state remains honest.
        if any(pattern.search(clean_text) for pattern in _NATAL_TEMPLATE_RESIDUE_PATTERNS):
            raise _NatalNarrativeError("schema_invalid")
        clean_text = re.sub(r"ответственой", "ответственной", clean_text, flags=re.IGNORECASE)
        if _CLOCK_TEXT_RE.search(clean_text) or _RELATIVE_DAY_RE.search(clean_text):
            raise _NatalNarrativeError("capability_violation")
        if _SPECIAL_POINT_RE.search(clean_text):
            mentioned = {
                _special_point_family(match.group(0))
                for match in _SPECIAL_POINT_RE.finditer(clean_text)
            }
            allowed = {
                _special_point_family(name) for name in available_special_points
            }
            if any(name not in allowed for name in mentioned):
                raise _NatalNarrativeError("claim_binding")
        if not _CYRILLIC_RE.search(clean_text):
            raise _NatalNarrativeError("capability_violation")
        paragraphs.append(
            TodaySphereNatalParagraph(text=clean_text, source_fact_ids=list(source_ids))
        )
    return TodaySphereNatalContent(paragraphs=paragraphs)


def _natal_error_code(exc: BaseException) -> str:
    if isinstance(exc, (asyncio.TimeoutError, TimeoutError)) or "timeout" in type(exc).__name__.casefold():
        return "timeout"
    if isinstance(exc, _NatalNarrativeError):
        return exc.code
    return "provider_error"


def _guarded_natal_log(
    event: str,
    *,
    level: str,
    sphere_key: str,
    prompt_version: str | None = None,
    latency_ms: int,
    paragraphs: int | None = None,
    error_code: str | None = None,
) -> None:
    try:
        with log_block(
            slice="W-TODAY-CONVERGENCE-P4",
            module="M-TODAY-SPHERE-NATAL-NARRATIVE",
            block="NATAL_GENERATION",
        ):
            payload: dict[str, Any] = {
                "sphere": sphere_key,
                "latency_ms": latency_ms,
            }
            if prompt_version is not None:
                payload["prompt_version"] = prompt_version
            if paragraphs is not None:
                payload["paragraphs"] = paragraphs
            if error_code is not None:
                payload["error_code"] = error_code
            log_event(event, level=level, payload=payload)
    except Exception:
        # Observability must never change the content outcome.
        pass


class TodaySpherePageService:
    def __init__(
        self,
        db: AsyncSession,
        *,
        llm: object | None = None,
        clock: Callable[[], datetime] | None = None,
        canon: TodayConvergenceCanon | None = None,
    ) -> None:
        self.db = db
        self.llm = llm
        self.clock = clock or (lambda: datetime.now(UTC))
        self.canon = canon or load_today_convergence_canon()

    # START_BLOCK: ACCESS_AND_DATE
    async def _load_user(self, user_id: UUID) -> User:
        result = await self.db.execute(
            select(User).where(User.id == user_id).options(selectinload(User.profile))
        )
        user = result.scalar_one_or_none()
        if user is None:
            raise ProfileIncompleteError()
        return user

    @staticmethod
    def _validate_profile(profile: UserProfile | None) -> UserProfile:
        if profile is None or not profile.is_onboarded:
            raw_missing = NatalContextService.missing_profile_fields(profile)
            raise ProfileIncompleteError(
                [f for f in raw_missing if not (f == "birth_time" and profile and profile.birth_time_mode in ("unknown", "bucket"))]
            )
        missing = [
            field for field in NatalContextService.missing_profile_fields(profile)
            if not (field == "birth_time" and profile.birth_time_mode in ("unknown", "bucket"))
        ]
        if missing:
            raise ProfileIncompleteError(missing)
        return profile

    async def get_page(
        self,
        user_id: UUID,
        sphere_key: str,
    ) -> TodaySpherePagePayload:
        # START_FUNCTION_CONTRACT: F-M-TODAY-SPHERE-PAGE.get_page
        # purpose: Authorize and build one static sphere page for the current
        #   local date without exposing Today snapshot evidence.
        # inputs: authenticated user UUID and canonical sphere key.
        # returns: TodaySpherePagePayload with natal and period layers.
        # side_effects: DB reads/cache write, one activation-layer request, and
        #   at most one bounded natal LLM request.
        # emitted_logs: sphere.natal_generation_completed,
        #   sphere.natal_generation_failed.
        # error_behavior: typed invalid/profile/access/timezone errors are left
        #   for the route to map; downstream generation failures are honest.
        # END_FUNCTION_CONTRACT: F-M-TODAY-SPHERE-PAGE.get_page
        normalized_sphere = sphere_key.strip().lower() if isinstance(sphere_key, str) else ""
        if normalized_sphere not in CANONICAL_SPHERES:
            raise InvalidSphereError(normalized_sphere)

        user = await self._load_user(user_id)
        profile = self._validate_profile(user.profile)
        try:
            target_date = resolve_user_local_date(user, self.clock())
        except UserLocalDateError as exc:
            raise InvalidUserTimezoneError(exc.code) from None

        access = await AccessService(self.db).can_access_day(user.id, target_date)
        if access.state == "locked":
            raise AccessRequiredError("access_required")

        birth_time_mode = profile.birth_time_mode
        if birth_time_mode not in ("exact", "bucket", "unknown"):
            birth_time_mode = "unknown"
        profile_hash = NatalContextService.compute_profile_hash(profile)
        period, period_unavailable = await self._build_period_layer(profile, target_date, normalized_sphere)
        natal = await self._build_natal_layer(
            user.id,
            profile,
            normalized_sphere,
            birth_time_mode,
            profile_hash,
        )
        return TodaySpherePagePayload(
            sphere=normalized_sphere,
            birth_time_mode=birth_time_mode,
            houses_available=birth_time_mode == "exact",
            natal=natal,
            period=period,
            period_identity="" if period_unavailable else _period_identity(
                period
            ),
            period_unavailable=period_unavailable,
            period_synthesis=None if period_unavailable else _period_synthesis(
                normalized_sphere,
                period,
                self.canon,
            ),
        )
    # END_BLOCK: ACCESS_AND_DATE

    # START_BLOCK: PERIOD_LAYER
    async def _build_period_layer(
        self,
        profile: UserProfile,
        target_date: date,
        sphere_key: str,
    ) -> tuple[list[TodaySpherePeriodItem], bool]:
        # START_FUNCTION_CONTRACT: F-M-TODAY-SPHERE-PAGE.build_period_layer
        # purpose: Fetch and deterministically project the four approved
        #   activation techniques for one sphere.
        # inputs: complete profile, user-local target date, and sphere key.
        # returns: at most five sorted period items plus sidecar-unavailable flag.
        # side_effects: exactly one SolarSage activation-layer request.
        # emitted_logs: none.
        # error_behavior: sidecar failures return empty layer with unavailable=true.
        # END_FUNCTION_CONTRACT: F-M-TODAY-SPHERE-PAGE.build_period_layer
        try:
            client = get_solarsage_client()
            raw_layer = await client.get_activation_layer(
                birth_date=profile.birthday.isoformat(),  # type: ignore[union-attr]
                birth_time=profile.birth_time.strftime("%H:%M") if profile.birth_time else "12:00",
                birth_lat=float(profile.birth_lat),  # type: ignore[arg-type]
                birth_lon=float(profile.birth_lon),  # type: ignore[arg-type]
                birth_tz=profile.birth_tz,  # type: ignore[arg-type]
                target_date=target_date.isoformat(),
                target_time="12:00",
                target_tz=profile.current_tz or profile.birth_tz or "UTC",
                house_system="PLACIDUS",
                techniques=list(PERIOD_TECHNIQUES),
            )
        except asyncio.CancelledError:
            raise
        except Exception:
            return [], True

        entries = _activation_entries(raw_layer)
        candidates: dict[str, _PeriodCandidate] = {}
        for entry in entries:
            technique = str(entry.get("technique", "")).strip().lower()
            if technique not in PERIOD_TECHNIQUES:
                continue
            target = _period_matches_sphere(entry, sphere_key, self.canon)
            if target is None:
                continue
            active_from = _safe_date(entry.get("active_from", entry.get("activeFrom")))
            active_until = _safe_date(entry.get("active_until", entry.get("activeUntil")))
            if active_from is None or active_until is None or active_until < active_from:
                continue
            target_kind, target_value = target
            item_id = _period_item_id(technique, f"{target_kind}:{target_value}", active_from)
            candidate = _PeriodCandidate(
                id=item_id,
                technique=technique,  # type: ignore[arg-type]
                title=_period_title(technique, target_kind, target_value),  # type: ignore[arg-type]
                note=_period_note(
                    sphere_key,
                    technique,  # type: ignore[arg-type]
                    target_kind,
                    target_value,
                ),
                target_kind=target_kind,
                target_value=target_value,
                active_from=active_from,
                active_until=active_until,
            )
            candidates[item_id] = candidate

        ordered = sorted(candidates.values(), key=lambda item: (item.active_until, item.id))[:5]
        return [
            TodaySpherePeriodItem(
                id=item.id,
                technique=item.technique,
                title=item.title,
                note=item.note,
                active_from=item.active_from,
                active_until=item.active_until,
            )
            for item in ordered
        ], False
    # END_BLOCK: PERIOD_LAYER

    # START_BLOCK: NATAL_CACHE
    async def _load_cached_natal(
        self,
        user_id: UUID,
        profile_hash: str,
        sphere_key: str,
        prompt_version: str,
    ) -> TodaySphereNatalContent | None:
        result = await self.db.execute(
            select(TodaySphereNatalNarrative).where(
                TodaySphereNatalNarrative.user_id == user_id,
                TodaySphereNatalNarrative.profile_hash == profile_hash,
                TodaySphereNatalNarrative.sphere_key == sphere_key,
                TodaySphereNatalNarrative.prompt_version == prompt_version,
            )
        )
        row = result.scalar_one_or_none()
        if row is None or row.content_json is None:
            return None
        try:
            content = TodaySphereNatalContent.model_validate(row.content_json)
            cleaned_paragraphs: list[TodaySphereNatalParagraph] = []
            for paragraph in content.paragraphs:
                clean_text = sanitize_narrative_text(paragraph.text)
                if clean_text is None or any(
                    pattern.search(clean_text)
                    for pattern in _NATAL_TEMPLATE_RESIDUE_PATTERNS
                ):
                    return None
                clean_text = re.sub(
                    r"ответственой", "ответственной", clean_text, flags=re.IGNORECASE
                )
                cleaned_paragraphs.append(paragraph.model_copy(update={"text": clean_text}))
            return content.model_copy(update={"paragraphs": cleaned_paragraphs})
        except Exception:
            return None

    async def _persist_natal(
        self,
        user_id: UUID,
        profile_hash: str,
        sphere_key: str,
        prompt_version: str,
        content: TodaySphereNatalContent,
    ) -> TodaySphereNatalContent:
        row = TodaySphereNatalNarrative(
            user_id=user_id,
            profile_hash=profile_hash,
            sphere_key=sphere_key,
            prompt_version=prompt_version,
            content_json=content.model_dump(by_alias=True),
        )
        self.db.add(row)
        try:
            await self.db.commit()
        except IntegrityError:
            await self.db.rollback()
        cached = await self._load_cached_natal(user_id, profile_hash, sphere_key, prompt_version)
        if cached is None:
            raise RuntimeError("sphere_natal_cache_write_failed")
        return cached
    # END_BLOCK: NATAL_CACHE

    # START_BLOCK: NATAL_GENERATION
    async def _build_natal_layer(
        self,
        user_id: UUID,
        profile: UserProfile,
        sphere_key: str,
        birth_time_mode: BirthMode,
        profile_hash: str,
    ) -> TodaySphereNatal:
        # START_FUNCTION_CONTRACT: F-M-TODAY-SPHERE-NATAL-NARRATIVE.build_natal_layer
        # purpose: Load or generate one profile/prompt/sphere keyed natal narrative.
        # inputs: user/profile identity, sphere, birth-time mode, and profile hash.
        # returns: ready claim-bound narrative or unavailable/null content.
        # side_effects: natal context read/build, one provider call, and an
        # insert-on-conflict cache write only after successful validation.
        # emitted_logs: sphere.natal_generation_completed,
        #   sphere.natal_generation_failed.
        # error_behavior: all expected generation/cache failures return unavailable.
        # END_FUNCTION_CONTRACT: F-M-TODAY-SPHERE-NATAL-NARRATIVE.build_natal_layer
        prompt_version = settings.today_sphere_natal_prompt_version
        cached = await self._load_cached_natal(
            user_id, profile_hash, sphere_key, prompt_version
        )
        if cached is not None:
            return TodaySphereNatal(state="ready", paragraphs=cached.paragraphs)

        started_at = time.monotonic()
        try:
            context = await NatalContextService(self.db).get_or_build_natal_context(user_id)
            if not isinstance(context, NatalContextData):
                context = NatalContextData.model_validate(context)
            fact_pack = build_sphere_natal_fact_pack(
                context,
                sphere_key,
                birth_time_mode,
                self.canon,
            )
            allowed_fact_ids = frozenset(
                fact["id"] for fact in fact_pack["facts"] if isinstance(fact, Mapping) and isinstance(fact.get("id"), str)
            )
            prompt = build_sphere_natal_prompt(fact_pack, sphere_key, prompt_version)
            provider = self.llm
            if provider is None:
                from app.services.llm_service import LLMService

                provider = LLMService()
            raw_response = await _call_natal_provider(provider, prompt)
            content = _validate_natal_provider_response(
                raw_response,
                allowed_fact_ids,
                frozenset(fact_pack["availableSpecialPoints"]),
            )
            persisted = await self._persist_natal(
                user_id,
                profile_hash,
                sphere_key,
                prompt_version,
                content,
            )
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            error_code = _natal_error_code(exc)
            _guarded_natal_log(
                "sphere.natal_generation_failed",
                level="warn",
                sphere_key=sphere_key,
                prompt_version=None,
                latency_ms=int((time.monotonic() - started_at) * 1000),
                error_code=error_code,
            )
            return TodaySphereNatal(state="unavailable", paragraphs=None)

        latency_ms = int((time.monotonic() - started_at) * 1000)
        _guarded_natal_log(
            "sphere.natal_generation_completed",
            level="info",
            sphere_key=sphere_key,
            prompt_version=prompt_version,
            latency_ms=latency_ms,
            paragraphs=len(persisted.paragraphs),
        )
        return TodaySphereNatal(state="ready", paragraphs=persisted.paragraphs)
    # END_BLOCK: NATAL_GENERATION


