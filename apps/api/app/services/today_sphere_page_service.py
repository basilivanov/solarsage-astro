@lru_cache(maxsize=1)
def _technical_sphere_definitions() -> dict[str, Mapping[str, Any]]:
    """Load the unchanged technical scoring canon used by period projection."""
    try:
        from app.services.canon_service import CANON_DIR

        path = Path(CANON_DIR) / "spheres.v1.yml"
        with path.open(encoding="utf-8") as stream:
            raw = yaml.safe_load(stream) or {}
    except (OSError, TypeError, ValueError, yaml.YAMLError):
        return {}

    spheres = raw.get("spheres") if isinstance(raw, Mapping) else None
    if not isinstance(spheres, Mapping):
        return {}
    return {
        str(technical_key).strip().lower(): definition
        for technical_key, definition in spheres.items()
        if isinstance(definition, Mapping)
    }


def _canonical_planet_name(value: object) -> str:
    return strip_prefix(str(value).strip()).upper() if value is not None else ""


def _canonical_sphere_or_raise(sphere_key: str, canon: TodayConvergenceCanon) -> str:
    normalized = sphere_key.strip().lower() if isinstance(sphere_key, str) else ""
    if normalized not in CANONICAL_SPHERES or normalized not in canon.canonical_spheres:
        raise InvalidSphereError(normalized)
    return normalized


def _house_numbers_for_sphere(
    sphere_key: str,
    canon: TodayConvergenceCanon,
) -> frozenset[int]:
    return frozenset(
        house
        for facet in canon.product_spheres[sphere_key].facets
        for house in facet.houses
    )


def _planet_technical_spheres(planet: str) -> frozenset[str]:
    """Return technical clusters that explicitly contain one planet."""
    normalized = _canonical_planet_name(planet)
    result: set[str] = set()
    for technical_key, definition in _technical_sphere_definitions().items():
        planets = definition.get("planets", ())
        if isinstance(planets, Mapping) and normalized in {
            _canonical_planet_name(name) for name in planets
        }:
            result.add(technical_key)
    return frozenset(result)


def _sphere_planets(sphere_key: str, canon: TodayConvergenceCanon) -> frozenset[str]:
    """Project the product sphere's allowed planet modifiers for natal facts."""
    return frozenset(
        _canonical_planet_name(planet)
        for facet in canon.product_spheres[sphere_key].facets
        for planet in facet.modifiers.get("planets", ())
    )


def _sphere_matches_planet(
    sphere_key: str,
    planet: str,
    canon: TodayConvergenceCanon,
) -> bool:
    """Map a period planet through technical clusters and product modifiers."""
    normalized = _canonical_planet_name(planet)
    technical_spheres = _planet_technical_spheres(normalized)
    product = canon.product_spheres[sphere_key]
    if any(
        technical_sphere in facet.technical_spheres
        for facet in product.facets
        for technical_sphere in technical_spheres
    ):
        return True
    return normalized in _sphere_planets(sphere_key, canon)


def _safe_date(value: object) -> date | None:
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    if isinstance(value, str):
        text = value.strip()
        if "T" in text:
            text = text.split("T", 1)[0]
        try:
            return date.fromisoformat(text)
        except ValueError:
            return None
    return None


def _activation_entries(raw_layer: object) -> list[Mapping[str, Any]]:
    if hasattr(raw_layer, "model_dump"):
        raw_layer = raw_layer.model_dump(by_alias=True)
    if isinstance(raw_layer, Mapping):
        raw_entries: object = raw_layer.get("activations")
        if raw_entries is None:
            raw_entries = raw_layer.get("evidence", raw_layer.get("items"))
        if raw_entries is None and "technique" in raw_layer:
            raw_entries = [raw_layer]
    elif isinstance(raw_layer, Sequence) and not isinstance(raw_layer, (str, bytes)):
        raw_entries = raw_layer
    else:
        return []
    if not isinstance(raw_entries, Sequence) or isinstance(raw_entries, (str, bytes)):
        return []
    return [entry for entry in raw_entries if isinstance(entry, Mapping)]


def _activation_target(entry: Mapping[str, Any]) -> tuple[Literal["planet", "house"], str] | None:
    target_type = str(entry.get("target_type", entry.get("targetType", ""))).strip().lower()
    target_key = entry.get("target_key", entry.get("targetKey"))
    raw_house = entry.get("house")
    if target_type == "house" or (not target_type and raw_house is not None):
        raw_value = raw_house if raw_house is not None else target_key
        try:
            return "house", str(int(raw_value))
        except (TypeError, ValueError):
            return None

    # Some sidecar period evidence carries a diagnostic house alongside a
    # planet target (for example a solar-return angular planet).  The explicit
    # target_type is authoritative; an unknown target kind is fail-closed.
    if target_type not in {"", "planet"}:
        return None

    target_text = str(target_key or entry.get("target_planet", "")).strip()
    if target_text.upper() in {"HOUSE", "HOUSES"}:
        try:
            return "house", str(int(raw_house if raw_house is not None else target_key))
        except (TypeError, ValueError):
            return None
    planet = _canonical_planet_name(target_text)
    return ("planet", planet) if planet else None


def _period_matches_sphere(
    entry: Mapping[str, Any],
    sphere_key: str,
    canon: TodayConvergenceCanon,
) -> tuple[Literal["planet", "house"], str] | None:
    target = _activation_target(entry)
    if target is None:
        return None
    target_kind, target_value = target
    if target_kind == "house":
        return target if int(target_value) in _house_numbers_for_sphere(sphere_key, canon) else None

    # Solar-return payloads may carry a diagnostic house alongside a planet.
    # That house is more specific than the planet's broad technical mapping.
    raw_house = entry.get("house")
    try:
        diagnostic_house = int(raw_house) if raw_house is not None else None
    except (TypeError, ValueError):
        diagnostic_house = None
    if diagnostic_house in _house_numbers_for_sphere(sphere_key, canon):
        return target
    return target if _sphere_matches_planet(sphere_key, target_value, canon) else None


