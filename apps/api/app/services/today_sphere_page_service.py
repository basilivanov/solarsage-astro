def _period_synthesis(
    sphere_key: str,
    items: Sequence[TodaySpherePeriodItem],
    canon: TodayConvergenceCanon,
) -> str | None:
    """Summarize the active period stack; empty layers remain explicitly null."""
    if not items:
        return None
    title = canon.product_spheres[sphere_key].title.casefold()
    if len(items) == 1:
        return f"Период «{items[0].title}» задаёт основной фон темы «{title}»."
    titles = ", ".join(item.title for item in items)
    effect = _SPHERE_PERIOD_EFFECTS.get(sphere_key, "тема усиливается через последовательные решения")
    return f"Одновременно действуют {len(items)} периода в теме «{title}»: {titles}. Их сумма: {effect}."


def _period_item_id(technique: str, target: str, active_from: date) -> str:
    value = f"{technique}|{target}|{active_from.isoformat()}"
    return hashlib.sha256(value.encode("utf-8")).hexdigest()[:32]


def _period_identity(items: Sequence[TodaySpherePeriodItem]) -> str:
    value = "|".join(
        f"{item.id}:{item.active_from.isoformat()}:{item.active_until.isoformat()}"
        for item in items
    )
    return hashlib.sha256(value.encode("utf-8")).hexdigest()[:32]


def _special_point_names(context: NatalContextData) -> tuple[str, ...]:
    return tuple(
        sorted(
            {
                _canonical_planet_name(point.name)
                for point in context.special_points
                if point.name and _canonical_planet_name(point.name)
            }
        )
    )


def _special_point_family(value: str) -> str:
    normalized = value.casefold()
    for family, aliases in _SPECIAL_POINT_FAMILIES.items():
        if any(alias in normalized for alias in aliases):
            return family
    return normalized


def _planet_fact(planet: NatalChartPlanet, *, include_house: bool) -> dict[str, Any]:
    name = _canonical_planet_name(planet.name)
    fact: dict[str, Any] = {
        "id": f"natal:planet:{name}",
        "kind": "planet",
        "name": name,
        "sign": planet.sign,
        "degree": planet.degree,
        "longitude": planet.longitude,
        "retrograde": planet.retrograde,
    }
    if include_house and planet.house is not None:
        fact["house"] = planet.house
    return fact


def build_sphere_natal_fact_pack(
    context: NatalContextData,
    sphere_key: str,
    birth_time_mode: BirthMode,
    canon: TodayConvergenceCanon | None = None,
) -> dict[str, Any]:
    # START_FUNCTION_CONTRACT: F-M-TODAY-SPHERE-NATAL-NARRATIVE.build_fact_pack
    # purpose: Project only the requested sphere's deterministic natal facts.
    # inputs: validated NatalContextData, canonical sphere key, birth-time mode,
    #   and optional loaded convergence canon.
    # returns: JSON-safe sphere-scoped pack with deterministic fact ids.
    # side_effects: none.
    # emitted_logs: none.
    # error_behavior: raises InvalidSphereError for a non-canonical sphere.
    # END_FUNCTION_CONTRACT: F-M-TODAY-SPHERE-NATAL-NARRATIVE.build_fact_pack
    active_canon = canon or load_today_convergence_canon()
    sphere = _canonical_sphere_or_raise(sphere_key, active_canon)
    exact = birth_time_mode == "exact"
    selected_planets = _sphere_planets(sphere, active_canon)
    related_houses = _house_numbers_for_sphere(sphere, active_canon) if exact else frozenset()

    planets = [
        _planet_fact(planet, include_house=exact)
        for planet in context.planets
        if _canonical_planet_name(planet.name) in selected_planets
    ]
    planets.sort(key=lambda fact: fact["id"])
    selected_ids = {fact["name"] for fact in planets}

    houses: list[dict[str, Any]] = []
    if exact:
        houses = [
            {
                "id": f"natal:house:{house.number}",
                "kind": "house",
                "number": house.number,
                "sign": house.sign,
                "degree": house.degree,
                "longitude": house.longitude,
            }
            for house in context.houses
            if house.number in related_houses
        ]
        houses.sort(key=lambda fact: (fact["number"], fact["id"]))

    aspects: list[dict[str, Any]] = []
    seen_aspects: set[str] = set()
    for aspect in context.aspects:
        planet_a = _canonical_planet_name(aspect.planet_a)
        planet_b = _canonical_planet_name(aspect.planet_b)
        if not ({planet_a, planet_b} & selected_ids):
            continue
        ordered = tuple(sorted((planet_a, planet_b)))
        if not all(ordered) or ordered[0] == ordered[1]:
            continue
        fact_id = f"natal:aspect:{ordered[0]}-{ordered[1]}"
        if fact_id in seen_aspects:
            continue
        seen_aspects.add(fact_id)
        aspects.append(
            {
                "id": fact_id,
                "kind": "aspect",
                "planetA": ordered[0],
                "planetB": ordered[1],
                "aspectType": aspect.aspect_type,
                "orb": aspect.orb,
                "applying": aspect.applying,
            }
        )
    aspects.sort(key=lambda fact: fact["id"])

    facts: list[dict[str, Any]] = [*planets, *houses, *aspects]
    score = context.sphere_scores.get(sphere)
    if score is not None:
        facts.append(
            {
                "id": f"natal:score:{sphere}",
                "kind": "score",
                "sphere": sphere,
                "value": score,
            }
        )

    dominant_names = [
        _canonical_planet_name(name)
        for name in context.dominants
        if _canonical_planet_name(name) in selected_ids
    ]
    dominant_names = sorted(set(dominant_names))

    return {
        "sphere": sphere,
        "birthTimeMode": birth_time_mode,
        "housesAvailable": exact,
        "facts": facts,
        "dominants": dominant_names,
        "availableSpecialPoints": list(_special_point_names(context)) if exact else [],
    }


