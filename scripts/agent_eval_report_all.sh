#!/usr/bin/env bash
# ############################################################################
# AI_HEADER: TOOL_AGENT_EVAL_REPORT_ALL
# ROLE: Regenerate every per-task agent-eval HTML report and the cross-task
#       summary in one command.
# DEPENDENCIES: bash, python3, scripts/agent_eval_report.py,
#               scripts/agent_eval_summary.py
# GRACE_ANCHORS: [EVAL_REPORT_ALL]
# ############################################################################

# START_MODULE_CONTRACT: M-AGENT-EVAL-REPORT-ALL
# purpose: One-command rebuild of all eval reports: for every evals/results/*/
#   directory containing metrics.json + review.json regenerate report.html via
#   agent_eval_report.py, then build evals/results/summary.html via
#   agent_eval_summary.py over all found runs.
# owns:
#   - scripts/agent_eval_report_all.sh
# inputs: none (fixed layout: evals/results/*/); optional
#   evals/results/summary-review.json enables the verdict/findings sections.
# outputs: regenerated report.html per run, evals/results/summary.html,
#   stdout list of written paths.
# dependencies: python3, scripts/agent_eval_report.py, scripts/agent_eval_summary.py
# side_effects: overwrites report.html in each run directory; a pre-existing
#   hand-written report.html (without the generator marker) is first copied to
#   report.manual.html as a one-time backup.
# emitted_logs: none
# invariants:
#   - directories without both metrics.json and review.json are skipped;
#   - missing summary-review.json is not an error (verdict section skipped);
#   - a hand-written report.html is never overwritten without a backup.
# failure_policy: non-zero exit if no complete run directory is found or any
#   generator invocation fails (set -euo pipefail).
# END_MODULE_CONTRACT: M-AGENT-EVAL-REPORT-ALL

# START_MODULE_MAP: M-AGENT-EVAL-REPORT-ALL
# public_entrypoints:
#   - main (no arguments)
# semantic_blocks:
#   - EVAL_REPORT_ALL: per-task regeneration loop plus summary build
# owned_tests: none (manual: run script, open printed summary.html path)
# END_MODULE_MAP: M-AGENT-EVAL-REPORT-ALL

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RESULTS_DIR="$REPO_ROOT/evals/results"
REPORT_PY="$REPO_ROOT/scripts/agent_eval_report.py"
SUMMARY_PY="$REPO_ROOT/scripts/agent_eval_summary.py"
SUMMARY_REVIEW="$RESULTS_DIR/summary-review.json"
SUMMARY_OUT="$RESULTS_DIR/summary.html"
GENERATED_MARKER="generated by scripts/agent_eval_report.py"

# START_BLOCK: EVAL_REPORT_ALL

runs=()
for dir in "$RESULTS_DIR"/*/; do
  dir="${dir%/}"
  [[ -f "$dir/metrics.json" && -f "$dir/review.json" ]] || continue

  if [[ -f "$dir/report.html" ]] \
    && ! grep -q "$GENERATED_MARKER" "$dir/report.html" \
    && [[ ! -f "$dir/report.manual.html" ]]; then
    cp "$dir/report.html" "$dir/report.manual.html"
    echo "backed up hand-written report: $dir/report.manual.html"
  fi

  python3 "$REPORT_PY" --run "$dir" --review "$dir/review.json" --out "$dir/report.html"
  runs+=("$dir")
done

if [[ ${#runs[@]} -eq 0 ]]; then
  echo "error: no run directories with metrics.json + review.json under $RESULTS_DIR" >&2
  exit 1
fi

summary_args=(--runs "${runs[@]}" --out "$SUMMARY_OUT")
if [[ -f "$SUMMARY_REVIEW" ]]; then
  summary_args+=(--review "$SUMMARY_REVIEW")
else
  echo "note: $SUMMARY_REVIEW not found — verdict/findings sections will be skipped"
fi
python3 "$SUMMARY_PY" "${summary_args[@]}"

echo "---"
echo "per-task reports:"
for dir in "${runs[@]}"; do
  echo "  $dir/report.html"
done
echo "summary:"
echo "  $SUMMARY_OUT"

# END_BLOCK: EVAL_REPORT_ALL
